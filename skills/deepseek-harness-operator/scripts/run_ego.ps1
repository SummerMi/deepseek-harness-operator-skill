<#
.SYNOPSIS
Run an ego-browser nodejs module with authenticated Harness URLs masked.

.DESCRIPTION
The connect module generated by harness_operator.py is safe by itself, but the
browser driver may echo the authenticated navigation URL in its own diagnostics.
Masking therefore belongs at this call layer, not only inside the module.
Always run connect modules through this script.

.PARAMETER Script
Absolute or relative path to the .mjs module to import.

.EXAMPLE
powershell -File scripts/run_ego.ps1 -Script "$env:USERPROFILE\.dsh\operator-private\codex-operator\connect-codex-operator.mjs"
#>
param([Parameter(Mandatory = $true)][string]$Script)

$ErrorActionPreference = 'Stop'

$absolute = (Resolve-Path -LiteralPath $Script).Path
$uri = [Uri]::new($absolute).AbsoluteUri

# ASCII-only entry point: PowerShell 5.1 mangles multi-line or quoted scripts.
$expression = "await import('$uri')"

# 2>&1 keeps diagnostic output in the same stream so every line can be masked.
$output = & ego-browser nodejs -e $expression 2>&1
$exitCode = $LASTEXITCODE

foreach ($line in $output) {
    $text = [string]$line

    # Authenticated entry point: keep scheme and origin, drop the credential tail.
    $text = $text -replace '(?i)(https?://[^\s"''<>/?#]+)[^\s"''<>]*[?#][^\s"''<>]*', '$1/[auth-redacted]'
    # Suspicious query parameters anywhere in plain text.
    $text = $text -replace '(?i)([?&#][A-Za-z0-9_-]*(?:token|key|secret|auth|ticket|code|session)[A-Za-z0-9_-]*=)[^&\s"''<>]+', '$1[redacted]'
    # userinfo in a URL.
    $text = $text -replace '(?i)(https?://)[^/\s"''<>]*@', '$1[redacted]@'

    Write-Output $text
}

exit $exitCode
